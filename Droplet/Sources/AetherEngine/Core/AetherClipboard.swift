import AppKit
import Foundation

/// Copies sensitive OTP codes, links, and recovery selections using host-only concealed
/// pasteboard types so Universal Clipboard and clipboard managers ignore them, with
/// configurable TTL and optional previous-clipboard restoration.
@MainActor
public final class AetherClipboard {
    private struct ClipboardSnapshot {
        let items: [[NSPasteboard.PasteboardType: Data]]
    }

    private let defaults: UserDefaults
    private var copied: (id: UUID?, change: Int)?
    private var clearTask: Task<Void, Never>?
    private var savedPrevious: ClipboardSnapshot?
    private let overrideClearDelay: TimeInterval?

    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let maxRestoreBytes = 4 * 1024 * 1024

    public init(defaults: UserDefaults, clearDelay: TimeInterval? = nil) {
        self.defaults = defaults
        self.overrideClearDelay = clearDelay
    }

    public func copy(_ text: String, id: UUID? = nil, pasteboard pb: NSPasteboard = .general) {
        clearTask?.cancel()
        clearTask = nil

        // Capture prior clipboard ONLY if it was not already set by AETHER or another password manager.
        if copied?.change != pb.changeCount {
            savedPrevious = Self.captureSnapshot(from: pb)
        }

        pb.prepareForNewContents(with: .currentHostOnly)
        pb.setString(text, forType: .string)
        pb.setString("", forType: .init("org.nspasteboard.ConcealedType"))
        pb.setString("", forType: .init("org.nspasteboard.TransientType"))
        let change = pb.changeCount
        copied = (id, change)

        guard defaults.bool(forKey: AetherPrefs.clearClipboard) else { return }
        let ttl = resolvedTTL()
        clearTask = Task { @MainActor [weak self, weak pb] in
            try? await Task.sleep(for: .seconds(ttl))
            guard !Task.isCancelled, let self, let pb, pb.changeCount == change else { return }
            if self.defaults.bool(forKey: AetherPrefs.restoreClipboard), let snapshot = self.savedPrevious {
                Self.restoreSnapshot(snapshot, to: pb)
            } else {
                pb.clearContents()
            }
            self.savedPrevious = nil
            self.copied = nil
            self.clearTask = nil
        }
    }

    public func clearIfOurs(ids: Set<UUID>? = nil, pasteboard pb: NSPasteboard = .general) {
        if let ids, copied?.id.map(ids.contains) != true { return }
        if copied?.change == pb.changeCount {
            clearTask?.cancel()
            clearTask = nil
            savedPrevious = nil
            copied = nil
            pb.clearContents()
        }
    }

    public func clearIfHolds(_ item: CodeItem, pasteboard pb: NSPasteboard = .general) {
        if holds(item, pasteboard: pb) {
            clearTask?.cancel()
            clearTask = nil
            savedPrevious = nil
            copied = nil
            pb.clearContents()
        }
    }

    public func holds(_ id: UUID, pasteboard pb: NSPasteboard = .general) -> Bool {
        copied?.id == id && copied?.change == pb.changeCount
    }

    public func holds(_ item: CodeItem, pasteboard pb: NSPasteboard = .general) -> Bool {
        holds(item.id, pasteboard: pb) && pb.string(forType: .string) == item.copyValue
    }

    public func stop() {
        clearTask?.cancel()
        clearTask = nil
        savedPrevious = nil
    }

    private func resolvedTTL() -> TimeInterval {
        overrideClearDelay ?? AetherPrefs.clipboardTTLSeconds(in: defaults)
    }

    private static func captureSnapshot(from pb: NSPasteboard) -> ClipboardSnapshot? {
        guard let items = pb.pasteboardItems, !items.isEmpty else { return nil }
        var totalBytes = 0
        var captured: [[NSPasteboard.PasteboardType: Data]] = []
        for item in items {
            let itemTypes = Set(item.types)
            if !itemTypes.isDisjoint(with: concealedTypes) {
                return nil
            }
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                totalBytes += data.count
                guard totalBytes <= maxRestoreBytes else { return nil }
                dict[type] = data
            }
            if !dict.isEmpty { captured.append(dict) }
        }
        return captured.isEmpty ? nil : ClipboardSnapshot(items: captured)
    }

    private static func restoreSnapshot(_ snapshot: ClipboardSnapshot, to pb: NSPasteboard) {
        pb.clearContents()
        let objects: [NSPasteboardItem] = snapshot.items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict {
                item.setData(data, forType: type)
            }
            return item
        }
        _ = pb.writeObjects(objects)
    }
}
