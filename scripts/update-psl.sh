#!/bin/bash
# Refreshes the bundled Public Suffix List (publicsuffix.org, maintained by Mozilla); install.sh runs it before a release.
# It is what tells "acme.co.uk" apart from "co.uk" and "evil.pages.dev" apart from "pages.dev".
set -euo pipefail
cd "$(dirname "$0")/.."
LIST=$(curl -fsSL https://publicsuffix.org/list/public_suffix_list.dat | grep -vE '^(//|[[:space:]]*$)' | sed 's/[[:space:]].*//')
# A captive portal or error page would replace the list with junk.
if [ "$(echo "$LIST" | wc -l)" -lt 5000 ] || ! grep -qx 'co\.uk' <<< "$LIST"; then
    echo "The download doesn't look like the Public Suffix List." >&2; exit 1
fi
{
    echo "// swift-format-ignore-file"
    echo "// Generated by scripts/update-psl.sh; do not edit."
    echo "// Public Suffix List, https://publicsuffix.org, under the Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/)."
    python3 -c '
import base64, hashlib, lzma, sys
raw = sys.stdin.read().encode("utf-8")
sha = hashlib.sha256(raw).hexdigest()
b64 = base64.b64encode(lzma.compress(raw, preset=9)).decode("ascii")
lines = "\n".join(b64[i:i+120] for i in range(0, len(b64), 120))
print(f"// Stored LZMA-compressed (sha256: {sha}) to minimize droplet binary footprint.")
print("import Foundation\n")
print("extension PublicSuffix {")
print("    static let list: String = {")
print("        let compressedBase64 = \"\"\"")
print(lines)
print("\"\"\"")
print("        guard let data = Data(base64Encoded: compressedBase64, options: .ignoreUnknownCharacters),")
print("              let rawData = try? (data as NSData).decompressed(using: .lzma) as Data,")
print("              let text = String(data: rawData, encoding: .utf8)")
print("        else { return \"\" }")
print("        return text")
print("    }()")
print("}")
' <<< "$LIST"
} > Droplet/Sources/CodeCatchCore/PublicSuffixList.swift
echo "$(echo "$LIST" | wc -l | tr -d ' ') rules"
